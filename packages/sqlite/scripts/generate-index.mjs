import { readdirSync, writeFileSync } from "node:fs";
import { dirname, join, relative } from "node:path";
import { fileURLToPath } from "node:url";

const packageRoot = join(dirname(fileURLToPath(import.meta.url)), "..");

const QUERY_ROOT = "src/queries";
const UTILS_PUBLIC = [
  "src/utils/emtpyDB.ts",
  "src/utils/removeDatabaseFile.ts",
  "src/utils/runMigrations.ts",
  "src/utils/useMigrationHelper.ts",
  "src/utils/initialize",
];

const collectTsFiles = (relativePath) => {
  const absolutePath = join(packageRoot, relativePath);
  const entries = readdirSync(absolutePath, { withFileTypes: true });
  const files = [];

  for (const entry of entries) {
    const child = join(relativePath, entry.name);
    if (entry.isDirectory()) {
      files.push(...collectTsFiles(child));
      continue;
    }
    if (!entry.isFile() || !entry.name.endsWith(".ts")) continue;
    if (entry.name.endsWith(".d.ts") || entry.name === "index.ts") continue;
    files.push(child);
  }

  return files;
};

const toModuleSpecifier = (fromDir, filePath) => {
  const specifier = relative(fromDir, filePath.replace(/\.ts$/, "")).replaceAll(
    "\\",
    "/"
  );
  return specifier.startsWith(".") ? specifier : `./${specifier}`;
};

const writeBarrel = (outputRelativePath, sourceFiles, fromDir) => {
  const lines = [
    "/** Auto-generated by scripts/generate-index.mjs. Do not edit. */",
    ...sourceFiles
      .toSorted((a, b) => a.localeCompare(b))
      .map((file) => `export * from "${toModuleSpecifier(fromDir, file)}";`),
    "",
  ];
  writeFileSync(join(packageRoot, outputRelativePath), lines.join("\n"));
};

const queryFiles = collectTsFiles(QUERY_ROOT);
const utilFiles = UTILS_PUBLIC.flatMap((path) =>
  path.endsWith(".ts") ? [path] : collectTsFiles(path)
);

writeBarrel("src/queries/index.ts", queryFiles, "src/queries");
writeBarrel("src/utils/index.ts", utilFiles, "src/utils");
writeFileSync(
  join(packageRoot, "index.ts"),
  [
    "/** Auto-generated by scripts/generate-index.mjs. Do not edit. */",
    'export * from "./src/data/settings";',
    'export * from "./src/queries";',
    'export * from "./src/schemas/app";',
    'export * from "./src/utils";',
    "",
  ].join("\n")
);

console.log(
  `Generated barrels: ${queryFiles.length} queries, ${utilFiles.length} utils`
);
